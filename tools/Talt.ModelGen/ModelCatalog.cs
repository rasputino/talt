using System.Globalization;
using System.Text;
using Talt.Core.Content;
using Talt.Core.Meshing.Models;
using Talt.Core.Towns;

namespace Talt.ModelGen;

/// <summary>One variant of a model key: its file and the palette indices with special roles.</summary>
internal sealed record ModelVariant(string File, IReadOnlyList<int> Paint, IReadOnlyList<int> Glow);

/// <summary>
/// Every generated model (file name → model) and the model keys that use them, as written to models.json
/// (contracts/model-pipeline.md).
/// </summary>
internal sealed class ModelCatalog
{
    public SortedDictionary<string, VoxModel> Files { get; } = new(StringComparer.Ordinal);

    public SortedDictionary<string, List<ModelVariant>> Keys { get; } = new(StringComparer.Ordinal);

    /// <summary>Builds all models from the game's building and industry data.</summary>
    public static ModelCatalog Build(IReadOnlyList<BuildingType> buildings, IReadOnlyList<IndustryKindDefinition> industries)
    {
        var catalog = new ModelCatalog();
        Vehicles.AddAll(catalog);
        Trains.AddAll(catalog);
        Nature.AddAll(catalog);
        foreach (var building in buildings)
        {
            Buildings.Add(catalog, building);
        }

        foreach (var industry in industries)
        {
            Industries.Add(catalog, industry);
        }

        return catalog;
    }

    /// <summary>Adds a model file under a key.</summary>
    public void Add(string key, string file, VoxelCanvas canvas, IReadOnlyList<int>? paint = null, IReadOnlyList<int>? glow = null)
    {
        if (!Files.TryAdd(file, canvas.Model))
        {
            throw new InvalidOperationException($"Model file '{file}' is generated twice.");
        }

        if (!Keys.TryGetValue(key, out var variants))
        {
            variants = [];
            Keys[key] = variants;
        }

        variants.Add(new ModelVariant(file, paint ?? [], glow ?? []));
    }

    /// <summary>The models.json text.</summary>
    public string AssignmentJson()
    {
        var text = new StringBuilder();
        text.Append("{\n");
        text.Append("  // Model assignment (feature 018, contracts/model-pipeline.md): model key -> variants. Generated by\n");
        text.Append("  // tools/Talt.ModelGen together with the .vox files in src/Talt.Client/Assets/Models; edit the models in\n");
        text.Append("  // MagicaVoxel and this file by hand when needed. \"paint\" indices take the object's colour, \"glow\"\n");
        text.Append("  // indices light up at night. Keys without an entry (for example station:<id>) use placeholders.\n");
        text.Append("  \"voxelsPerTile\": 8,\n");
        text.Append("  \"models\": {\n");
        var first = true;
        foreach (var (key, variants) in Keys)
        {
            if (!first)
            {
                text.Append(",\n");
            }

            first = false;
            text.Append("    \"").Append(key).Append("\": [\n");
            for (var i = 0; i < variants.Count; i++)
            {
                var v = variants[i];
                text.Append("      { \"file\": \"").Append(v.File).Append('"');
                if (v.Paint.Count > 0)
                {
                    text.Append(", \"paint\": [").Append(string.Join(", ", v.Paint.Select(p => p.ToString(CultureInfo.InvariantCulture)))).Append(']');
                }

                if (v.Glow.Count > 0)
                {
                    text.Append(", \"glow\": [").Append(string.Join(", ", v.Glow.Select(p => p.ToString(CultureInfo.InvariantCulture)))).Append(']');
                }

                text.Append(" }").Append(i < variants.Count - 1 ? ",\n" : "\n");
            }

            text.Append("    ]");
        }

        text.Append("\n  }\n}\n");
        return text.ToString();
    }
}
